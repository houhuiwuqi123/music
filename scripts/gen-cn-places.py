def km(a, b):
    la1, lo1, la2, lo2 = map(math.radians, (*a, *b))
    h = math.sin((la2-la1)/2)**2 + math.cos(la1)*math.cos(la2)*math.sin((lo2-lo1)/2)**2
    return 6371 * 2 * math.asin(math.sqrt(h))
table = {}
for p, c in pairs:
    if p == '0': continue
    P = norm(p)
    if c == '0':
        table[P] = capitals[P]; continue
    key = P + '|' + norm(c)
    if key in manual:
        table[key] = manual[key]; continue
    k = next(k for k in keys(c) if k in coords)
    lon, lat = coords[k]
    table[key] = (lat, lon)
    dist = km((lat, lon), capitals[P])
    limit = 1500 if P in ('新疆', '西藏', '内蒙古') else (900 if P in ('青海', '黑龙江', '甘肃', '四川', '云南', '海南') else 450)
    if dist > limit: print('FAR', key, k, (lat, lon), int(dist))
for p in capitals: table.setdefault(p, capitals[p])
