d = tempfile.mkdtemp()
for name, url in SOURCES.items():
    print('download', url, file=sys.stderr)
    urllib.request.urlretrieve(url, os.path.join(d, name))
pairs = set()
with open(os.path.join(d, 'ipv4_source.txt'), encoding='utf-8') as f:
    for line in f:
        parts = line.rstrip('\n').split('|')
        if len(parts) >= 5 and parts[2] == '中国':
            pairs.add((parts[3], parts[4]))
pairs = sorted(pairs)
coords = json.load(open(os.path.join(d, 'city_coordinates.json'), encoding='utf-8'))  # name -> [lon, lat]
def norm(n):
    for s in ('特别行政区', '省', '市'):
        if n.endswith(s) and len(n) > len(s): n = n[:-len(s)]
    return n
SUFFIX = re.compile(r'(特别行政区|维吾尔自治区|壮族自治区|回族自治区|自治区|省|市|地区|盟|林区)$')
